export const QUESTIONS: GameQuestion[] = groups.flatMap(group => group.questions.map((text, index) => ({
  id: `${group.topic}-${index + 1}`, text, topics: [group.topic], featured: group.featuredIds.includes(index + 1),
})));

export function normalizeQuestionTopics(value: unknown): QuestionTopicId[] {
  return Array.isArray(value) ? QUESTION_TOPICS.map(topic => topic.id).filter(id => value.includes(id)) : [];
}
export function validQuestionTopics(value: unknown): boolean {
  return value === undefined || (Array.isArray(value) && value.length <= QUESTION_TOPICS.length &&
    value.every(id => QUESTION_TOPICS.some(topic => topic.id === id)));
}
// An empty selection means All topics, including rooms created before topic selection existed.
export function questionsForTopics(value: unknown): GameQuestion[] {
  const selected = normalizeQuestionTopics(value);
  return selected.length ? QUESTIONS.filter(question => question.topics.some(topic => selected.includes(topic))) : QUESTIONS;
}

export function questionTopicsRejection(room: { host?: string; phase?: string; questionTopics?: unknown }, pid: string, value: unknown): 'invalid_question_topics' | 'host_only_setting' | 'question_topics_locked' | null {
  if (!validQuestionTopics(value)) return 'invalid_question_topics';
  if (value === undefined || normalizeQuestionTopics(value).join(',') === normalizeQuestionTopics(room.questionTopics).join(',')) return null;
  if (room.host !== pid) return 'host_only_setting';
  if (room.phase !== 'lobby') return 'question_topics_locked';
  return null;
}
